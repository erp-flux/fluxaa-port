"""Version 1.4 — database guards of the new records, and the catalogue changes applied to the ports already
bootstrapped (the bootstrap never overwrites what a port holds):

* the tank readings, their reviews, the pumping readings, the checklist answers and signatures are append-only;
  the pumping sheets and the checklists are never deleted;
* every port gets the default readers of the live reports (ReportAccess) when it has none;
* the laboratory's quality certificate is read by the terminal, the owner / charterer side, the vessel, the
  surveyor and the port only (readers limited to that list); the time sheet is read by every party and may be
  generated by the agency, the terminal or the ship; the pumping log document type is created;
* the agency may provide the statutory certificates on the master's behalf (task M0:03, co-role AGE) — on the
  published template version and on the pending tasks of the calls that are not declared yet.

Each change is applied only where the port still holds the catalogue's former value, so that a port
administrator's own settings are kept.
"""
from django.db import migrations

from apps.core.dbguards import REFUSE_FUNCTION, append_only_sql, drop_sql, no_delete_sql

APPEND_ONLY = ["registry_tankreading", "registry_tankreadingreview", "registry_safetycheckanswer",
               "registry_safetychecklistsignature"]
NO_DELETE = ["registry_pumpinglogsheet", "registry_safetychecklist"]

DEFAULT_REPORT_READERS = {
    "PUMPING_LOG": ["NAV", "TER", "CAP", "INS", "COM", "DIR", "AGE"],
    "MEASUREMENTS": ["NAV", "TER", "CAP", "INS", "COM", "DIR", "AGE"],
    "SAFETY_CHECKLIST": ["NAV", "TER", "CAP", "APO", "INS", "AGE", "SUR", "DIR"],
    "CALL_BOARD": ["AGE", "TER", "CAP", "APO", "SVC", "ADM", "SUR", "INS", "COM", "PRE", "DIR"],
}


def install(apps, schema_editor):
    if schema_editor.connection.vendor != "postgresql":
        return
    statements = [REFUSE_FUNCTION]
    for table in APPEND_ONLY:
        statements += append_only_sql(table)
    for table in NO_DELETE:
        statements += no_delete_sql(table)
    with schema_editor.connection.cursor() as cursor:
        for sql in statements:
            cursor.execute(sql)


def uninstall(apps, schema_editor):
    if schema_editor.connection.vendor != "postgresql":
        return
    with schema_editor.connection.cursor() as cursor:
        for table in APPEND_ONLY + NO_DELETE:
            for sql in drop_sql(table):
                cursor.execute(sql)


